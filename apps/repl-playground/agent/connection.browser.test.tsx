import { expect, it } from 'vitest'
import { commands, page } from 'vitest/browser'

import { mountPlayground } from './browser.fixture'

// https://github.com/moeru-ai/auv/pull/414#discussion_r4399104804
it('retains ACP connections across view remounts, creates fresh sessions and recovers from failed startup', async () => {
  const app = await mountPlayground(true)
  await expect.element(page.getByRole('button', { exact: true, name: 'Connect' })).toBeVisible()
  // A token can rotate after discovery. Each connection needs a live token,
  // rather than the one the account held when the form mounted.
  sessionStorage.setItem('exterior.accessToken', 'connection-token')
  const initial = await commands.agentFixtureState()
  await page.getByRole('button', { exact: true, name: 'Connect' }).click()
  await expect.element(page.getByRole('textbox', { name: 'Message the agent' })).toBeVisible()
  const connected = await commands.agentFixtureState()
  expect(connected.ticketRequests).toBe(1)
  expect(connected.connections).toBe(1)
  expect(connected.registrations).toHaveLength(initial.registrations.length + 1)
  // ROOT CAUSE: the runtime hook tied a single-use agent connection to mount
  // effects. Rebuilding its view disconnected the process behind the ticket.
  app.remount()
  await expect.element(page.getByRole('textbox', { name: 'Message the agent' })).toBeVisible()
  const remounted = await commands.agentFixtureState({ discoverTools: true })
  expect(remounted.ticketRequests).toBe(1)
  expect(remounted.connections).toBe(1)
  expect(remounted.registrations).toHaveLength(initial.registrations.length + 1)
  expect(remounted.tools[0].name).toBe('execute')
  expect(remounted.messages).toEqual(expect.arrayContaining([expect.objectContaining({ method: 'session/new', params: expect.objectContaining({ cwd: app.cwd }) })]))
  const sessions = remounted.messages.filter(message => message.method === 'session/new').length
  await page.getByRole('tab', { exact: true, name: 'Script' }).click()
  await page.getByRole('tab', { exact: true, name: 'Agent' }).click()
  await page.getByRole('textbox', { name: 'Message the agent' }).fill('Check the connection')
  await page.getByRole('button', { exact: true, name: 'Send' }).click()
  await expect.element(page.getByText('Connected through the test ACP peer.', { exact: true })).toBeVisible()
  const prompted = await commands.agentFixtureState()
  expect(prompted.registrations).toContain('Bearer connection-token')
  expect(prompted.connections).toBe(connected.connections)
  expect(prompted.messages.filter(message => message.method === 'session/new')).toHaveLength(sessions)
  expect(prompted.messages.find(message => message.method === 'session/prompt')?.params.prompt).toEqual([{ text: 'Check the connection', type: 'text' }])
  document.querySelector('[data-agent-activity]')!.scrollIntoView()
  await commands.agentScreenshot('connected')
  await page.viewport(1280, 720)
  expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(window.innerWidth)
  await page.getByRole('button', { exact: true, name: 'Start a new agent session' }).click()
  await expect.element(page.getByText('Connected through the test ACP peer.', { exact: true })).not.toBeInTheDocument()
  await page.getByRole('textbox', { name: 'Message the agent' }).fill('Check the new session')
  await page.getByRole('button', { exact: true, name: 'Send' }).click()
  await expect.element(page.getByText('Connected through the test ACP peer.', { exact: true })).toBeVisible()
  const renewed = await commands.agentFixtureState()
  const prompts = renewed.messages.filter(message => message.method === 'session/prompt')
  expect(prompts).toHaveLength(2)
  expect(prompts[0].params.sessionId).not.toBe(prompts[1].params.sessionId)
  expect(prompts[1].params.prompt).toEqual([{ text: 'Check the new session', type: 'text' }])
  expect(renewed.messages.some(message => message.method === 'session/list')).toBe(false)

  await page.getByRole('button', { exact: true, name: 'Disconnect' }).click()
  await commands.agentFixtureState({ supported: false })
  const newSessions = renewed.messages.filter(message => message.method === 'session/new').length
  await page.getByRole('button', { exact: true, name: 'Connect' }).click()
  await expect.element(page.getByText('This agent does not support HTTP MCP.', { exact: false })).toBeVisible()
  await expect.element(page.getByRole('textbox', { name: 'Message the agent' })).not.toBeInTheDocument()
  expect((await commands.agentFixtureState()).messages.filter(message => message.method === 'session/new')).toHaveLength(newSessions)
  await page.getByRole('button', { exact: true, name: 'Disconnect' }).click()
  const beforeFailure = await commands.agentFixtureState({ startupError: true })
  await page.getByRole('button', { exact: true, name: 'Connect' }).click()
  await expect.element(page.getByText('Agent startup failed', { exact: true })).toBeVisible()
  expect((await commands.agentFixtureState()).ticketRequests).toBe(beforeFailure.ticketRequests + 1)
  await commands.agentFixtureState({ startupError: false, supported: true })
  await page.getByRole('button', { exact: true, name: 'Reconnect' }).click()
  await expect.element(page.getByRole('textbox', { name: 'Message the agent' })).toBeVisible()
  expect((await commands.agentFixtureState()).ticketRequests).toBe(beforeFailure.ticketRequests + 2)
  await page.getByRole('button', { exact: true, name: 'Disconnect' }).click()
  const beforeCancel = await commands.agentFixtureState({ holdTicket: true })
  await page.getByRole('button', { exact: true, name: 'Connect' }).click()
  await expect.poll(async () => (await commands.agentFixtureState()).ticketRequests).toBe(beforeCancel.ticketRequests + 1)
  await page.getByRole('button', { exact: true, name: 'Disconnect' }).click()
  await page.getByRole('button', { exact: true, name: 'Connect' }).click()
  await commands.agentFixtureState({ releaseTicket: true })
  await expect.element(page.getByRole('textbox', { name: 'Message the agent' })).toBeVisible()
  const afterCancel = await commands.agentFixtureState()
  expect(afterCancel.connections).toBe(beforeCancel.connections + 1)
  expect(afterCancel.errors).toEqual([])
})
